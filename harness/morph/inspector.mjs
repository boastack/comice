import { chromium, webkit, devices } from 'playwright'
let failed = false
// Browsers to run: `node harness/morph/inspector.mjs webkit iphone` (default all).
const projects = process.argv.slice(2).length ? process.argv.slice(2) : ['chromium','webkit','iphone']
for (const name of projects) {
  const browser = await (name === 'chromium' ? chromium : webkit).launch()
  const page = await browser.newPage(name === 'iphone' ? { ...devices['iPhone 15'], deviceScaleFactor: 1 } : { viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 })
  page.setDefaultTimeout(30000)
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('https://fonts.googleapis.com/**',r=>r.abort())
  try {
    await page.goto('http://localhost:8750/demo/morph/',{waitUntil:'domcontentloaded'})
    await page.waitForFunction(async () => window.__demos?.length === (await import('/demo/morph/examples.js')).examples.length)
    await page.evaluate(async()=>{(await import('comice')).setAdaptiveQuality(false)})
    const scrollToStage=async(id,fraction=.5)=>{
      await page.evaluate(({id,fraction})=>{const e=__demos.find(e=>e.id===id);const s=e.section;scrollTo(0,s.offsetTop+(s.offsetHeight-innerHeight)*fraction)}, {id,fraction})
      await page.waitForFunction(id=>(__demos.find(e=>e.id===id)).panel.querySelector('.status').textContent==='Live',id)
      await page.waitForFunction(({id,fraction})=>{const e=__demos.find(e=>e.id===id);return e.driver!=='scroll'||Math.abs(e.handle.progress-fraction)<.025},{id,fraction})
    }
    console.log(name,'scroll'); await scrollToStage('hero-merge',.2)
    const initial=await page.evaluate(()=>__demos[2].handle.progress)
    await scrollToStage('hero-merge',.8)
    const later=await page.evaluate(()=>__demos[2].handle.progress)
    if(initial>.25||later<.75)throw Error(`Demo does not follow scroll ${initial}/${later}`)
    if(await page.locator('[name=progress],.scrubber,[name=play]').count())throw Error('Progress controls remain')
    if(await page.locator('#collection input, #collection select').count())throw Error('Inline demo settings remain')
    await page.getByRole('button',{name:'Morph settings',exact:true}).click()
    await scrollToStage('hero-merge',.8)
    if(await page.locator('#inspector').evaluate(el=>el.getBoundingClientRect().width)!==256)throw Error('Inspector width changed')
    console.log(name,'controls'); await page.getByLabel('Liquid',{exact:true}).fill('0.31')
    await page.waitForFunction(()=>__demos[2].options.liquid===.31)
    await page.getByLabel('Liquid',{exact:true}).press('ArrowRight')
    await page.waitForFunction(()=>Math.abs(__demos[2].options.liquid-.32)<.001)
    await page.getByLabel('Join style',{exact:true}).selectOption('slab')
    await page.getByLabel('Sag',{exact:true}).fill('11')
    await page.waitForFunction(()=>__demos[2].options.join.sag===11)
    await page.getByLabel('Automatic width',{exact:true}).first().uncheck()
    await page.getByLabel('Width',{exact:true}).first().fill('12')
    await page.waitForFunction(()=>__demos[2].options.join.width===12)
    await page.getByLabel('Connection points',{exact:true}).fill('[[0.2,0.5],[0.5,0.5],[0.8,0.5]]')
    await page.getByLabel('Connection points',{exact:true}).press('Tab')
    await page.waitForFunction(()=>__demos[2].options.join.points?.length===3)
    await page.locator('[data-group=glass] summary').click()
    await page.getByLabel('Enable glass',{exact:true}).check()
    await page.getByLabel('Directional light',{exact:true}).fill('0.12')
    await page.waitForFunction(()=>__demos[2].options.glass.rim===.12)
    await page.locator('[data-group=interaction] summary').click()
    await page.getByLabel('Enable pointer',{exact:true}).check()
    await page.getByLabel('Wake',{exact:true}).fill('5')
    await page.waitForFunction(()=>__demos[2].options.interaction.wake===5)
    await page.locator('[data-group=maskRasterization] summary').click()
    await page.getByLabel('Shape fill',{exact:true}).fill('0.91')
    await page.waitForFunction(()=>__demos[2].options.maskRasterization.fill===.91)
    await page.getByLabel('Raster resolution',{exact:true}).fill('[0,0]')
    await page.getByLabel('Raster resolution',{exact:true}).press('Tab')
    if(!await page.locator('.inspector-error').textContent())throw Error('Invalid resolution was accepted')
    if(await page.evaluate(()=>__demos[2].options.maskRasterization.resolution)!==undefined)throw Error('Invalid settings replaced the live configuration')
    await page.getByLabel('Raster resolution',{exact:true}).fill('[512,288]')
    await page.getByLabel('Raster resolution',{exact:true}).press('Tab')
    await page.waitForFunction(()=>__demos[2].options.maskRasterization.resolution?.[0]===512)
    // Settings stay with the current demo rather than being applied globally.
    console.log(name,'persistence'); await scrollToStage('circles')
    await page.waitForFunction(()=>document.querySelector('.active-demo').textContent==='Circle Breakout')
    if(await page.locator('[data-group=motion]').getAttribute('open')===null)throw Error('New demo lost its default expanded controls')
    if(await page.evaluate(()=>__demos[3].options.liquid)!==.85)throw Error('Settings leaked to another demo')
    await scrollToStage('hero-merge')
    await page.waitForFunction(()=>document.querySelector('.active-demo').textContent==='Hero Merge')
    if(await page.evaluate(()=>__demos[2].options.liquid)!==.32)throw Error('Demo settings were lost')
    // Each alternative uses its native core driver and is reflected in copied code.
    console.log(name,'drivers'); for(const driver of ['hover','click','drag','audio','scroll']) {
      console.log(name,driver); await page.getByLabel('Animation input',{exact:true}).selectOption(driver)
      await page.waitForFunction(driver=>__demos[2].driver===driver&&/^(Live|Press the sound)/.test(__demos[2].panel.querySelector('.status').textContent),driver)
      const snapshot=await page.evaluate(()=>({driver:__demos[2].driver,code:__demos[2].panel.querySelector('code').textContent}))
      if(!snapshot.code.includes(`.driver(${driver}(`))throw Error('Code uses the wrong driver')
      if(driver==='hover'){
        await page.evaluate(()=>{const e=__demos[2],r=e.media.getBoundingClientRect();e.media.parentElement.dispatchEvent(new PointerEvent('pointermove',{clientX:r.left+r.width/2,clientY:r.top+r.height/2,bubbles:true}))})
        await page.waitForFunction(()=>__demos[2].handle.progress>.8)
      }
      if(driver==='click'){
        await page.evaluate(()=>{const e=__demos[2],r=e.media.getBoundingClientRect();e.media.parentElement.dispatchEvent(new MouseEvent('click',{clientX:r.left+r.width/2,clientY:r.top+r.height/2,bubbles:true}))})
        await page.waitForFunction(()=>__demos[2].handle.progress>.8)
      }
      if(driver==='audio'){
        // Where the browser let the music start, the soundtrack's energy must reach progress.
        if(await page.evaluate(()=>!document.querySelector('#soundtrack').paused))
          await page.waitForFunction(()=>__demos[2].effect.params.getParam('progress')>.02,null,{timeout:15000})
        if(!snapshot.code.includes(".map('bass').to(effect, 'progress'")||!snapshot.code.includes(".map('high').to(effect, 'velocity'"))throw Error('Audio code is missing its mapping')
      }
      if(driver==='drag'){
        await page.evaluate(()=>{const e=__demos[2],r=e.media.getBoundingClientRect(),target=e.media.parentElement;for(const [type,x]of[['pointerdown',.1],['pointermove',.6],['pointerup',.6]])target.dispatchEvent(new PointerEvent(type,{clientX:r.left+r.width*x,clientY:r.top+r.height/2,pointerId:1,bubbles:true}))})
        await page.waitForFunction(()=>__demos[2].handle.progress>.3)
      }
    }
    console.log(name,'reset'); await page.getByRole('button',{name:'Reset demo',exact:true}).click()
    await page.waitForFunction(()=>__demos[2].options.liquid===.85&&__demos[2].driver==='scroll')
    await page.keyboard.press('Escape')
    if(await page.locator('#inspector').isVisible())throw Error('Escape did not close settings')
    if(await page.getByRole('button',{name:'Morph settings',exact:true}).getAttribute('aria-expanded')!=='false')throw Error('Toggle state not restored')
    // Every demo's From and To live in Settings > Shapes. Upload both endpoints.
    await page.getByRole('button',{name:'Morph settings',exact:true}).click()
    await page.locator('[data-group=shapes] summary').click()
    await page.getByLabel('Upload From SVG',{exact:true}).setInputFiles({name:'from.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><circle cx="50" cy="50" r="40"/></svg>')})
    await page.waitForFunction(()=>__demos[2].options.from?.includes('<circle'))
    await page.getByLabel('Upload To SVG',{exact:true}).setInputFiles({name:'to.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect x="10" y="10" width="80" height="80"/></svg>')})
    await page.waitForFunction(()=>__demos[2].options.to?.includes('<rect'))
    await page.getByLabel('To',{exact:true}).fill('polygon(50% 100%,0% 25%,50% 0%,100% 25%)')
    await page.getByRole('button',{name:'Apply shapes',exact:true}).click()
    await page.waitForFunction(()=>__demos[2].options.to?.startsWith('polygon(')&&__demos[2].options.from?.includes('<circle'))
    // A shape that cannot load reports in Settings and Reset brings the originals back.
    await page.getByLabel('To',{exact:true}).fill('not a shape')
    await page.getByRole('button',{name:'Apply shapes',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.inspector-error').textContent.includes('not a shape'))
    await page.getByLabel('To',{exact:true}).fill('polygon(50% 100%,0% 25%,50% 0%,100% 25%)')
    await page.getByRole('button',{name:'Apply shapes',exact:true}).click()
    await page.waitForFunction(()=>__demos[2].options.to?.startsWith('polygon(')&&!document.querySelector('.inspector-error').textContent)
    await page.keyboard.press('Escape')
    await scrollToStage('hero-merge')
    const copied=await page.evaluate(async()=>{
      const e=__demos[2],code=e.panel.querySelector('code').textContent;e.handle.destroy()
      const core=await import('comice'),{morph}=await import('@comice/morph')
      const run=new(Object.getPrototypeOf(async function(){}).constructor)('comice','scroll','morph',code.replace(/^import .*$/gm,'')+'\nreturn {handle,effect}')
      const result=await run(core.comice,core.scroll,morph);e.handle=result.handle;e.effect=result.effect
      await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('Copied demo did not become ready')),10000);e.handle.on('ready',()=>{clearTimeout(timer);resolve()});e.handle.on('error',(_,event)=>{clearTimeout(timer);reject(event.error)})})
      return {progress:e.handle.progress,code}
    })
    if(!copied.code.includes('polygon(')||copied.progress<.45||copied.progress>.55)throw Error('Copied uploaded SVG/CSS demo differs')
    await page.getByRole('button',{name:'Morph settings',exact:true}).click()
    await page.getByRole('button',{name:'Reset demo',exact:true}).click()
    await page.waitForFunction(()=>__demos[2].options.to===undefined&&__demos[2].options.from==='../assets/images/shelf.svg')
    await page.keyboard.press('Escape')
    if(await page.locator('#settings-toggle').count()!==1||await page.locator('[data-settings-for]').count())throw Error('Duplicate Settings controls remain')
    await page.getByRole('button',{name:'Morph settings',exact:true}).click()
    await page.getByLabel('Choose demo',{exact:true}).selectOption('circles')
    await scrollToStage('circles')
    await page.waitForFunction(()=>document.querySelector('.active-demo').textContent==='Circle Breakout')
    const gap=await page.evaluate(()=>{const e=__demos.find(e=>e.id==='circles'),f=e.frame.getBoundingClientRect(),h=e.section.querySelector('.copy').getBoundingClientRect();return {gap:f.top-h.bottom,bottom:f.bottom,height:innerHeight}})
    if(gap.gap<44||gap.bottom>gap.height)throw Error(`Heading and image are too close, or the image runs off screen (${gap.gap}px)`)
    await page.keyboard.press('Escape')
    // Code opens from the toolbar button beside Settings and follows the demo on screen.
    if(await page.locator('.expand-code, .code-bar:visible, #collection pre:visible').count())throw Error('Inline code remains')
    await page.getByRole('button',{name:'Show code',exact:true}).click()
    await page.waitForFunction(()=>!document.querySelector('#code-card').hidden&&document.querySelector('#code-card .code-title').textContent==='Circle Breakout'&&document.querySelector('#code-card code').textContent.includes('circles-media'))
    await page.getByRole('button',{name:'Morph settings',exact:true}).click()
    if(!await page.locator('#code-card').isHidden())throw Error('Code and Settings panels overlap')
    await page.keyboard.press('Escape')
    await page.getByRole('button',{name:'Show code',exact:true}).click()
    await page.keyboard.press('Escape')
    if(!await page.locator('#code-card').isHidden())throw Error('Escape did not close the code card')
    if(!await page.evaluate(()=>document.fonts.check('500 16px Geist')))throw Error('Geist failed to load')
    const bounds=await page.evaluate(()=>__demos.every(e=>{const f=e.frame.getBoundingClientRect(),s=e.section.querySelector('.sticky').getBoundingClientRect();return f.height<=s.height&&f.top>=s.top-1&&f.bottom<=s.bottom+1}))
    if(!bounds)throw Error('A visual escaped its stage or overlapped the code')
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Horizontal overflow')
    await page.evaluate(()=>__demos.forEach(e=>e.handle?.destroy()))
    if(await page.locator('canvas').count())throw Error('Teardown leaked canvases')
    if(errors.length)throw Error(errors.join('\n'))
    console.log('PASS',name,'256px inspector, scroll, all drivers, parameters, keyboard, per-demo persistence, shapes, code card, copied code and teardown')
  }catch(error){failed=true;console.error('FAIL',name,error.stack)}finally{await browser.close()}
}
process.exitCode=failed?1:0
